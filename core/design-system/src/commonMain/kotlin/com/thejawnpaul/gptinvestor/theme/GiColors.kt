// Lets existing MaterialTheme.colorScheme reads pick up palette v3 while screens migrate to GiTheme.colors.
fun GiColors.toColorScheme(): ColorScheme {
    val base = if (isDark) darkColorScheme() else lightColorScheme()
    return base.copy(
        primary = primary,
        onPrimary = onPrimary,
        primaryContainer = violetSoft,
        onPrimaryContainer = violet,
        secondary = violet,
        onSecondary = onViolet,
        secondaryContainer = violetSoft,
        onSecondaryContainer = violet,
        // Legacy screens use tertiary only for premium and locked UI, which v4 draws as a violet-soft banner.
        tertiary = primary,
        onTertiary = onPrimary,
        tertiaryContainer = violetSoft,
        onTertiaryContainer = ink,
        background = bg,
        onBackground = ink,
        surface = bg,
        onSurface = ink,
        surfaceVariant = tile,
        onSurfaceVariant = muted,
        surfaceContainerLowest = raised,
        surfaceContainerLow = raised,
        surfaceContainer = raised,
        surfaceContainerHigh = raised,
        surfaceContainerHighest = tile,
        outline = control,
        outlineVariant = line,
        error = error,
        onError = onPrimary,
        errorContainer = errorSoft,
        onErrorContainer = error,
        inverseSurface = ink,
        inverseOnSurface = bg,
        inversePrimary = violet,
        surfaceTint = Color.Transparent,
        scrim = scrim,
    )
}
